"""Naming what is in front of the target.

Knowing the product is worth a request because it decides which spellings are
worth trying first, and the answer is remembered for the rest of the run. The
signatures are wafw00f's, so these tests check that the shapes it wrote survive
being carried over: a header the product sets, a cookie only it plants, a string
it puts in the page.

The negative cases matter as much. Generic refusal wording is what a great many
filters say, and a signature set that matches it would attribute every refusal to
whichever product happened to be listed first.
"""

from __future__ import annotations

import unittest

from injectorkit.core.httpmsg import Headers, Response
from injectorkit.engine.bypass import (
    BLOCK_STATUSES,
    RefusalSignature,
    classify_refusal,
    identify_vendor,
    refusal_signature,
)


def response(status: int = 403, headers=None, body: bytes = b"") -> Response:
    return Response(status=status, headers=Headers(headers or []), body=body)


class NamingTheProduct(unittest.TestCase):
    def test_cloudflare_by_its_header(self):
        self.assertEqual(identify_vendor(response(headers=[("cf-ray", "7d3f2a1b8c9d-LAX")])), "Cloudflare")

    def test_cloudflare_by_its_server_header(self):
        self.assertEqual(identify_vendor(response(headers=[("Server", "cloudflare")])), "Cloudflare")

    def test_cloudflare_by_its_cookie(self):
        self.assertEqual(
            identify_vendor(response(headers=[("Set-Cookie", "__cfduid=abc; path=/")])), "Cloudflare"
        )

    def test_sucuri_by_its_header(self):
        self.assertEqual(identify_vendor(response(headers=[("X-Sucuri-ID", "11001")])), "Sucuri CloudProxy")

    def test_barracuda_by_its_cookie(self):
        self.assertEqual(
            identify_vendor(response(headers=[("Set-Cookie", "barra_counter_session=xyz")])),
            "Barracuda",
        )

    def test_safeline_by_its_body(self):
        self.assertEqual(identify_vendor(response(body=b"<html>SafeLine</html>")), "SafeLine")

    def test_modsecurity_by_its_body(self):
        self.assertEqual(
            identify_vendor(response(body=b"This error was generated by Mod_Security")), "ModSecurity"
        )

    def test_the_name_does_not_have_to_match_case(self):
        self.assertEqual(identify_vendor(response(headers=[("SERVER", "CloudFlare")])), "Cloudflare")

    def test_a_successful_response_names_nothing(self):
        # A product's fingerprints appear on what it serves instead of the page.
        self.assertEqual(identify_vendor(response(status=200, headers=[("cf-ray", "abc")])), "")


class WhatMustNotBeMistakenForAProduct(unittest.TestCase):
    """Generic refusal wording belongs to no product in particular."""

    def test_request_blocked_is_not_a_vendor(self):
        self.assertEqual(identify_vendor(response(body=b"Request blocked: not allowed")), "")

    def test_access_denied_is_not_a_vendor(self):
        self.assertEqual(identify_vendor(response(body=b"<h1>Access Denied</h1>")), "")

    def test_a_lab_filter_with_waf_in_its_name_is_not_guessed(self):
        self.assertEqual(identify_vendor(response(body=b"blocked (lab-waf)")), "")

    def test_an_ordinary_page_names_nothing(self):
        self.assertEqual(identify_vendor(response(body=b"<html>hello</html>")), "")


class DecidingWhetherItWasRefused(unittest.TestCase):
    """Strict on purpose: a false positive escalates every later payload."""

    def test_a_block_status_with_refusal_wording_is_a_refusal(self):
        probe = response(status=403, body=b"Access Denied - request blocked")
        refused, _, signature = classify_refusal(None, probe)
        self.assertTrue(refused)
        self.assertEqual(signature.statuses, [403])
        self.assertTrue(signature.wording)

    def test_a_vendor_fingerprint_is_conclusive_on_its_own(self):
        probe = response(status=403, headers=[("cf-ray", "abc")], body=b"")
        refused, vendor, _ = classify_refusal(None, probe)
        self.assertTrue(refused)
        self.assertEqual(vendor, "Cloudflare")

    def test_the_same_status_as_the_baseline_is_not_a_refusal(self):
        # An application that answers 403 to everything has refused nothing.
        baseline = response(status=403, body=b"nope")
        probe = response(status=403, body=b"Access Denied")
        refused, _, _ = classify_refusal(baseline, probe)
        self.assertFalse(refused)

    def test_a_block_status_without_refusal_wording_is_not_a_refusal(self):
        probe = response(status=403, body=b"<html>you are not an admin</html>")
        refused, _, _ = classify_refusal(None, probe)
        self.assertFalse(refused)

    def test_an_ordinary_status_change_is_not_a_refusal(self):
        probe = response(status=404, body=b"not found")
        refused, _, _ = classify_refusal(response(status=200), probe)
        self.assertFalse(refused)

    def test_a_crash_is_not_a_refusal(self):
        # The origin erroring out says nothing about whether input was filtered.
        probe = response(status=500, body=b"Access Denied")
        refused, _, _ = classify_refusal(None, probe)
        self.assertFalse(refused)

    def test_the_block_statuses_are_the_ones_a_filter_uses(self):
        self.assertTrue({403, 406, 419, 501, 999} <= BLOCK_STATUSES)


class RememberingWhatARefusalLooksLike(unittest.TestCase):
    def test_a_signature_matches_its_own_status(self):
        signature = refusal_signature(response(status=406, body=b"Not Acceptable"))
        self.assertTrue(signature.matches(response(status=406)))

    def test_a_signature_matches_its_wording_on_another_status(self):
        signature = refusal_signature(response(status=403, body=b"Access Denied"))
        self.assertTrue(signature.matches(response(status=418, body=b"Access Denied again")))

    def test_a_signature_does_not_match_an_unrelated_response(self):
        signature = refusal_signature(response(status=403, body=b"Access Denied"))
        self.assertFalse(signature.matches(response(status=200, body=b"<html>fine</html>")))

    def test_an_empty_signature_is_not_known(self):
        self.assertFalse(RefusalSignature().known)


if __name__ == "__main__":
    unittest.main()
