"""The bypass subsystem: how a value gets past a filter, and what is remembered.

Two jobs, both engine-level so no module has to think about them.

The first is to keep a filter profile per target: which spellings were refused,
which were rewritten, and at which generation a value started to reach the
parser. Detection is deliberately conservative, because a false positive is
expensive - every later action would climb generations for nothing.

The second is to make escalation affordable. Once generation 2 is known to pass
for a target, the next action starts there instead of rediscovering the fact,
which is what turns a ladder into a budget.
"""

from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass, field

from .blackboard import Blackboard, Confidence
from .evidence import refused as looks_refused
from ..core.httpmsg import Response


# What a refusal looks like. A status code a WAF uses and an application would
# not produce by accident, or wording that only a refusal carries.
#
# Both halves are needed, which is the whole point. "The response changed" is not
# a refusal: applications change their own responses all the time, and treating
# that as a block escalates every later payload through generations of mutation
# for nothing. A block status that the baseline did not also answer with, or a
# page that says something refused the request.
BLOCK_STATUSES = frozenset({403, 406, 419, 501, 999})

REFUSAL_WORDING = (
    "access denied",
    "request rejected",
    "request blocked",
    "not acceptable",
    "security policy",
    "blocked",
    "forbidden",
    "incident id",
    "请求被拦截",
    "访问被拒绝",
    "非法请求",
    "拦截",
)

# What a filter leaves in a response that names it.
#
# The question this answers is narrow: is something filtering, and which family
# of rules is it - because that decides which spellings are worth trying next.
# Naming every product that exists does not help with that, so the list is short
# on purpose and every entry is a single mark a product puts on a response it is
# in front of: a header it sets, a cookie only it plants, wording it serves.
#
# Generic refusal wording ("request blocked", "access denied") is deliberately
# absent. A great many filters say it, and matching it would attribute every
# refusal to whichever product happened to be listed first. Where a product is
# only recognisable from a combination, all of the combination is required.
#
# wafw00f (https://github.com/EnableSecurity/wafw00f) is the reference tool for
# this question and was consulted for it; the entries here were chosen for this
# decision and reduced to marks, not taken as a plugin's decision procedure.
#
# (header name, pattern) pairs matched against the response headers, with the
# pattern treated as a regular expression, case-insensitively.
VENDOR_HEADERS: tuple[tuple[str, tuple[tuple[str, str], ...]], ...] = (
    ("Cloudflare", (("server", r"cloudflare"), ("cf-ray", r".+?"))),
    ("Sucuri CloudProxy", (("x-sucuri-id", r".+?"), ("x-sucuri-cache", r".+?"), ("server", r"sucuri(\-cloudproxy)?"))),
    ("Fastly", (("x-fastly-request-id", r"\w+"), ("x-served-by", r"^cache-[a-z]{3}\d+-[A-Z]{3}"))),
    ("Safedog", (("server", r"safedog"),)),
    ("Wordfence", (("server", r"wf[_\-]?waf"),)),
    ("ModSecurity", (("server", r"(mod_security|noyb)"),)),
)

# Cookie names a product plants. Matched against Set-Cookie.
VENDOR_COOKIES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Cloudflare", (r"^__cfduid",)),
    ("Incapsula", (r"^incap_ses.*?=", r"^visid_incap.*?=")),
    ("Barracuda", (r"^barra_counter_session=", r"^bni__barracuda_lb_cookie=", r"^bni_persistence=")),
    ("Safedog", (r"^safedog\-flow\-item=",)),
    ("Citrix NetScaler", (r"^ns_af=", r"^citrix_ns_id", r"^nsc_")),
    ("DenyAll", (r"^sessioncookie=",)),
)

# Strings the product puts in the page it serves instead.
VENDOR_BODY: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("SafeLine", (r"safeline", r"<!\-\-\sevent id:")),
    ("Sucuri CloudProxy", (r"access denied.{0,6}?sucuri website firewall", r"cloudproxy@sucuri\.net")),
    ("Wordfence", (r"generated by wordfence", r"broke one of (the )?wordfence (advanced )?blocking rules")),
    ("Barracuda", (r"barracuda\.networks",)),
    ("ModSecurity", (r"this error was generated by mod.?security", r"protected by mod.?security", r"modsecurity iis")),
    ("Incapsula", (r"incapsula incident id", r"powered by incapsula", r"/_incapsula_resource")),
    ("Safedog", (r"safedogsite/broswer_logo\.jpg", r"404\.safedog\.cn/sitedog_stat\.html")),
)


@dataclass
class RefusalSignature:
    """What this target's refusal looks like, so later ones are recognised.

    Learned from the first refusal rather than guessed at, and used from then on:
    a target that refuses one payload a particular way refuses the next one the
    same way, and matching that is cheaper and more accurate than re-deciding
    what a refusal is for every response.
    """

    statuses: list[int] = field(default_factory=list)
    wording: list[str] = field(default_factory=list)

    def matches(self, response: Response) -> bool:
        if response.status in self.statuses:
            return True
        if not self.wording:
            return False
        body = response.text.lower()
        return any(marker in body for marker in self.wording)

    @property
    def known(self) -> bool:
        return bool(self.statuses or self.wording)


def identify_vendor(response: Response) -> str:
    """Name the product in front of the target, when the response names it.

    Three places, in the order wafw00f checks them: a header the product sets, a
    cookie only it plants, a string it puts in the page. Headers first because
    they are the cheapest to check and the hardest for anything else to produce
    by accident.
    """
    if response.status < 400:
        return ""
    body = response.text[:8000]
    cookies = response.headers.get("Set-Cookie") or ""

    for vendor, markers in VENDOR_HEADERS:
        for name, pattern in markers:
            value = response.headers.get(name)
            if value and re.search(pattern, value, re.I):
                return vendor

    for vendor, patterns in VENDOR_COOKIES:
        if any(re.search(pattern, cookies, re.I) for pattern in patterns):
            return vendor

    for vendor, patterns in VENDOR_BODY:
        if any(re.search(pattern, body, re.I) for pattern in patterns):
            return vendor

    return ""


def refusal_signature(response: Response) -> RefusalSignature:
    """The parts of a refusal worth remembering."""
    wording = [marker for marker in REFUSAL_WORDING if marker in response.text.lower()]
    statuses = [response.status] if response.status in BLOCK_STATUSES else []
    return RefusalSignature(statuses=statuses, wording=wording)


def classify_refusal(baseline: Response | None, probe: Response) -> tuple[bool, str, RefusalSignature]:
    """Whether a probe was refused, by whom, and what the refusal looks like.

    Deliberately strict, because a false positive is expensive: it escalates
    every later payload through generations of mutation that were never needed.
    A vendor fingerprint on a refusal is conclusive. Otherwise the status has to
    have changed into one only a filter uses, and the page has to read like a
    refusal rather than like the application saying no for its own reasons.
    """
    vendor = identify_vendor(probe)

    if vendor and probe.status >= 400:
        return True, vendor, refusal_signature(probe)

    # A crash is not a refusal. The origin erroring out says nothing about
    # whether input was filtered, and treating it as a block pushes every payload
    # up a generation for no reason.
    if probe.status >= 500 and probe.status != 501:
        return False, vendor, RefusalSignature()

    baseline_status = baseline.status if baseline is not None else 0
    if probe.status == baseline_status or probe.status not in BLOCK_STATUSES:
        return False, vendor, RefusalSignature()

    signature = refusal_signature(probe)
    if signature.wording:
        return True, vendor, signature
    return False, vendor, RefusalSignature()


@dataclass
class FilterProfile:
    """What one host does with input it does not like."""

    host: str
    vendor: str = ""
    refusals: int = 0
    rewrites: int = 0
    observed: bool = False
    # Whether a probe was sent to find out rather than waiting to be refused.
    probed: bool = False
    # What a refusal from this target looks like, once one has been seen.
    signature: RefusalSignature = field(default_factory=RefusalSignature)
    # Per action family, the generation known to get through.
    floors: dict[str, int] = field(default_factory=dict)
    refused_values: list[str] = field(default_factory=list)

    @property
    def protected(self) -> bool:
        return bool(self.vendor) or self.refusals >= 2

    def floor(self, action: str) -> int:
        return self.floors.get(action, 0)

    def raise_floor(self, action: str, generation: int) -> None:
        """Only ever upwards: one pass is evidence the spelling works, a later
        refusal is not evidence it stopped working."""
        if generation > self.floors.get(action, 0):
            self.floors[action] = generation

    def describe(self) -> str:
        state = "protected" if self.protected else "open"
        vendor = f" ({self.vendor})" if self.vendor else ""
        floors = ", ".join(f"{key}=gen{value}" for key, value in sorted(self.floors.items()))
        return f"{self.host}: {state}{vendor}, refusals={self.refusals}, floors=[{floors}]"


class Bypass:
    """Owns filter profiles and decides when to escalate."""

    def __init__(self, blackboard: Blackboard, max_generation: int = 3, enabled: bool = True) -> None:
        self.blackboard = blackboard
        self.max_generation = max_generation
        self.enabled = enabled
        self.profiles: dict[str, FilterProfile] = {}
        # Per host and action, the mutators already proven to be refused. A
        # filter that is case-insensitive defeats case-swap once; there is no
        # reason for the next payload to pay for that discovery again.
        self.dead_mutators: dict[str, set[str]] = {}

    # ------------------------------------------------------------ persistence

    def to_json(self) -> str:
        """What this run learned about how hosts treat input they dislike.

        Worth keeping between runs because all of it is bought with refused
        requests: the refusal count, the refused spellings and the generation
        floor are earned one rejection at a time, and re-earning them costs
        exactly what they cost the first time. The board facts derived from them
        are not enough - the thresholds behind those facts are the part that has
        to survive.
        """
        return json.dumps(
            {
                "profiles": {host: asdict(profile) for host, profile in self.profiles.items()},
                "dead_mutators": {key: sorted(names) for key, names in self.dead_mutators.items()},
            },
            indent=2,
        )

    def load_json(self, text: str) -> int:
        """Merge remembered profiles in. Returns how many hosts were loaded."""
        try:
            raw = json.loads(text)
        except ValueError:
            return 0
        if not isinstance(raw, dict):
            return 0

        loaded = 0
        profiles = raw.get("profiles")
        if isinstance(profiles, dict):
            for host, data in profiles.items():
                if not isinstance(data, dict):
                    continue
                signature = data.get("signature") or {}
                self.profiles[host] = FilterProfile(
                    host=host,
                    vendor=str(data.get("vendor", "")),
                    refusals=int(data.get("refusals", 0)),
                    rewrites=int(data.get("rewrites", 0)),
                    observed=bool(data.get("observed", False)),
                    probed=bool(data.get("probed", False)),
                    signature=RefusalSignature(
                        statuses=[int(s) for s in (signature.get("statuses") or [])],
                        wording=[str(w) for w in (signature.get("wording") or [])],
                    ),
                    floors={str(k): int(v) for k, v in (data.get("floors") or {}).items()},
                    refused_values=[str(value) for value in (data.get("refused_values") or [])],
                )
                loaded += 1

        dead = raw.get("dead_mutators")
        if isinstance(dead, dict):
            for key, names in dead.items():
                if isinstance(names, list):
                    self.dead_mutators.setdefault(key, set()).update(str(name) for name in names)
        return loaded

    # ---------------------------------------------------------------- profile

    def profile(self, host: str) -> FilterProfile:
        if host not in self.profiles:
            self.profiles[host] = FilterProfile(host=host)
        return self.profiles[host]

    def floor(self, host: str, action: str) -> int:
        return self.profile(host).floor(action) if self.enabled else 0

    def raise_floor(self, host: str, action: str, generation: int) -> None:
        if not self.enabled or generation <= 0:
            return
        profile = self.profile(host)
        profile.raise_floor(action, generation)
        self.blackboard.set(
            f"bypass.floor.{host}.{action}",
            generation,
            evidence=f"generation {generation} reached the target",
            confidence=Confidence.LIKELY,
        )

    # ------------------------------------------------------------- observing

    def mutator_dead(self, host: str, action: str, name: str, scope: str = "") -> bool:
        return name in self.dead_mutators.get(self._dead_key(host, action, scope), ())

    def mark_mutator_dead(self, host: str, action: str, name: str, scope: str = "") -> None:
        """Remember a rewrite this target refuses, so nothing spells it again.

        The scope narrows the claim. A rewrite that failed on a `gopher://`
        payload says nothing about the same rewrite on an `http://` one: the
        filter caught a literal that only one of them carries.
        """
        if not self.enabled or not name:
            return
        key = self._dead_key(host, action, scope)
        self.dead_mutators.setdefault(key, set()).add(name)
        self.blackboard.set(
            f"bypass.dead.{host}.{action}{('.' + scope) if scope else ''}",
            sorted(self.dead_mutators[key]),
            evidence=f"{name} was refused by the filter",
            confidence=Confidence.LIKELY,
        )

    @staticmethod
    def _dead_key(host: str, action: str, scope: str) -> str:
        return f"{host}|{action}|{scope}" if scope else f"{host}|{action}"

    def observe(self, host: str, action: str, response: Response, request_label: str = "") -> bool:
        """Record what a response says about the filter. Returns True on refusal."""
        profile = self.profile(host)
        profile.observed = True
        if _refused(response):
            profile.refusals += 1
            if request_label:
                # Bounded: a long run must not grow this without limit.
                if len(profile.refused_values) < 100:
                    profile.refused_values.append(request_label)
            # Learn the shape of a refusal the first time one is seen, rather
            # than re-deciding what a refusal is for every later response. A
            # target that refuses one payload this way refuses the next one the
            # same way, and matching is both cheaper and more accurate.
            if not profile.signature.known:
                profile.signature = refusal_signature(response)
            vendor = identify_vendor(response)
            if vendor and not profile.vendor:
                profile.vendor = vendor
                self.blackboard.set(
                    f"filter.vendor.{host}",
                    vendor,
                    evidence=f"the refusal names it: {response.status}",
                    confidence=Confidence.LIKELY,
                )
            self.blackboard.set(
                f"filter.refused.{host}",
                profile.refusals,
                evidence=f"{request_label or 'probe'} was refused with status {response.status}",
                confidence=Confidence.LIKELY,
            )
            return True
        return False

    # -------------------------------------------------------------- probing

    def needs_probe(self, host: str) -> bool:
        """Whether the target has been asked yet whether anything is filtering."""
        return self.enabled and not self.profile(host).probed

    def record_probe(self, host: str, vendor: str, signature: RefusalSignature) -> None:
        """Remember what the probe concluded, including that nothing was found.

        Recording the negative matters as much as the positive: a host that was
        asked and answered is not asked again, and "no filter" is an answer.
        """
        profile = self.profile(host)
        profile.probed = True
        if vendor:
            profile.vendor = vendor
        if signature.known and not profile.signature.known:
            profile.signature = signature
        if vendor or signature.known:
            profile.refusals = max(profile.refusals, 1)

    def summarise(self) -> str:
        if not self.profiles:
            return "no target observed"
        return "; ".join(profile.describe() for profile in self.profiles.values())

    def refusals(self) -> int:
        """How many requests the target refused outright."""
        return sum(profile.refusals for profile in self.profiles.values())

    def filter_class(self, host: str) -> str:
        """A short name for what is in front of this host.

        What a run learns about rewrites belongs to a *class* of target rather
        than to one target: a spelling that beat one product's rules is worth
        trying first against the same product somewhere else, and one that failed
        against a target with no filter says nothing about any other. So the
        name has to be of the kind of filter, and a target that has none is its
        own kind rather than an unknown one.
        """
        profile = self.profile(host)
        if profile.vendor:
            return profile.vendor.lower().replace(" ", "-")
        if profile.signature.known:
            marks = [str(status) for status in profile.signature.statuses[:2]]
            return "filtered-" + "-".join(marks) if marks else "filtered-wording"
        return "unfiltered"

    def blocked_families(self) -> dict[str, int]:
        """Which payload families are closed, and how many rewrites proved it.

        This is the difference between "nothing here" and "everything here is
        filtered": a run that found nothing because every spelling was refused
        has to say so, or its silence reads as a clean target.
        """
        out: dict[str, int] = {}
        for key, names in self.dead_mutators.items():
            parts = key.split("|")
            scope = parts[2] if len(parts) > 2 and parts[2] else "any"
            out[scope] = out.get(scope, 0) + len(names)
        return out


def _refused(response: Response) -> bool:
    """Whether a response looks like something refused the request.

    Delegated rather than reimplemented. This is the copy the ladder actually
    reads - every time a response comes back - while the judge's is only reached
    when a module asks. While they were separate, a fix applied to the judge's
    looked like a fix and changed nothing on the path that matters.
    """
    return looks_refused(response)
